  p_entity text,
  p_from text,
  p_to text,
  p_allowed text[]
)
returns void
language plpgsql
immutable
as $$
begin
  if p_from = p_to then
    return;
  end if;
  if not (p_to = any(p_allowed)) then
    raise exception '% cannot move from % to %', p_entity, p_from, p_to
      using errcode = 'check_violation';
  end if;
end;
$$;


