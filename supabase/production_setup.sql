-- in Zod, using the configurable minimums from system_settings.
-- ---------------------------------------------------------------------------
create or replace function validate_investor_subscription()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_category investor_category;
  v_min_units numeric;
  v_unit_price numeric;
